/** 昵称清理：去掉重复键、空串和多余空格 */
export function normalizeAliases(map = EXTRA_ALIASES) {
  const out = {};
  for (const [code, list] of Object.entries(map)) {
    const key = String(code).trim();
    if (!key) continue;
    const set = new Set([...(out[key] || [])]);
    for (const a of list || []) {
      const v = String(a).trim();
      if (v) set.add(v);
    }
    out[key] = [...set];
  }
  return out;
}
